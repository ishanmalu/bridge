fn find(f: impl Fn(&(u16, u16, u16)) -> bool) -> Option<&'static (u16, u16, u16)> {
    TABLE.iter().find(|r| f(r))
}

#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
pub fn hid_from_mac(vk: u16) -> Option<u16> {
    find(|r| r.1 == vk).map(|r| r.0)
}
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
pub fn mac_from_hid(hid: u16) -> Option<u16> {
    find(|r| r.0 == hid && r.1 != NONE).map(|r| r.1)
}
#[cfg_attr(not(windows), allow(dead_code))]
pub fn hid_from_win(scan: u16) -> Option<u16> {
    find(|r| r.2 == scan).map(|r| r.0)
}
#[cfg_attr(not(windows), allow(dead_code))]
pub fn win_from_hid(hid: u16) -> Option<u16> {
    find(|r| r.0 == hid && r.2 != NONE).map(|r| r.2)
}

/// Cmd on a Mac and Ctrl on a PC do the same jobs, so swap them when the two sides differ.
/// Mac → PC: Cmd becomes Ctrl, Ctrl becomes Win. PC → Mac: the reverse. Alt/Option stay put.
pub fn swap_cmd_ctrl(hid: u16) -> u16 {
    match hid {
        LCTRL => LGUI,
        LGUI => LCTRL,
        RCTRL => RGUI,
        RGUI => RCTRL,
        h => h,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_round_trip() {
        for hid in 0x04..=0x1D {
            assert_eq!(hid_from_mac(mac_from_hid(hid).unwrap()), Some(hid));
            assert_eq!(hid_from_win(win_from_hid(hid).unwrap()), Some(hid));
        }
    }

    #[test]
    fn no_duplicate_hids() {
        let mut seen = std::collections::HashSet::new();
        for r in TABLE {
            assert!(seen.insert(r.0), "duplicate hid {:#x}", r.0);
        }
    }

    #[test]
    fn cmd_c_becomes_ctrl_c() {
        let cmd = hid_from_mac(0x37).unwrap();
        assert_eq!(win_from_hid(swap_cmd_ctrl(cmd)), Some(0x1D));
    }
}
